#!/usr/bin/env bash
# ONE-TIME, on the VPS, from the app directory (e.g. /opt/mms):
#   DOMAIN=example.com bash deploy/vps/setup-tunnel.sh
#   (add HOST_PREFIX=mms- if you use one — see deploy/hosts.sh)
#
# 1. Logs cloudflared into your Cloudflare account (prints a URL — open it in
#    any browser and pick $DOMAIN's zone).
# 2. Creates a tunnel named "mms" (skipped if it already exists here).
# 3. Points each *-api hostname's DNS at the tunnel.
# 4. Writes deploy/cloudflared/config.yml mapping each hostname to its service.
# Safe to re-run: it reuses the tunnel and overwrites the DNS records/config.
set -euo pipefail
cd "$(dirname "$0")/../.."
source deploy/hosts.sh

DIR="$PWD/deploy/cloudflared"
IMAGE=cloudflare/cloudflared:2026.9.3
mkdir -p "$DIR"

cf() {
  docker run --rm -it -u root -e HOME=/root \
    -v "$DIR:/root/.cloudflared" "$IMAGE" "$@"
}

[ -f "$DIR/cert.pem" ] || cf tunnel login

if [ ! -f "$DIR/credentials.json" ]; then
  cf tunnel create --credentials-file /root/.cloudflared/credentials.json mms
fi
TUNNEL_ID=$(grep -o '"TunnelID":"[^"]*"' "$DIR/credentials.json" | cut -d'"' -f4)
echo "tunnel: $TUNNEL_ID"

for svc in "${!API_HOST[@]}"; do
  cf tunnel route dns --overwrite-dns "$TUNNEL_ID" "${API_HOST[$svc]}"
done

{
  echo "# Generated by deploy/vps/setup-tunnel.sh — re-run it to change."
  echo "tunnel: $TUNNEL_ID"
  echo "credentials-file: /etc/cloudflared/credentials.json"
  echo "ingress:"
  for svc in "${!API_HOST[@]}"; do
    echo "  - hostname: ${API_HOST[$svc]}"
    echo "    service: http://${svc}:${API_PORT[$svc]}"
  done
  echo "  - service: http_status:404"
} > "$DIR/config.yml"

# cert.pem is only needed for the admin commands above, not to run the tunnel.
# The container runs as uid 65532 (nonroot) and must read the other two.
docker run --rm -u root -v "$DIR:/d" --entrypoint sh busybox -c \
  'chown 65532:65532 /d/config.yml /d/credentials.json && chmod 400 /d/credentials.json && chmod 600 /d/cert.pem'

echo "Done. deploy/cloudflared/config.yml:"
cat "$DIR/config.yml"
