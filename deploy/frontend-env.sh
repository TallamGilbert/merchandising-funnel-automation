#!/usr/bin/env bash
# Writes frontends/<app>/.env.production.local with the production backend
# URLs. NEXT_PUBLIC_* values are inlined at `next build` time, so this must
# run before building. .env.production.local beats a dev .env.local, so this
# is safe to run on a dev machine too (both files are gitignored).
#
#   DOMAIN=example.com [HOST_PREFIX=mms-] bash deploy/frontend-env.sh
set -euo pipefail
cd "$(dirname "$0")/.."
source deploy/hosts.sh

# Every app's user menu links to the others (@mms/ui apps.ts).
APP_URLS=(
  "NEXT_PUBLIC_EXECUTIVE_DASHBOARD_APP_URL=$(app_url executive-dashboard)"
  "NEXT_PUBLIC_VENDOR_MANAGEMENT_APP_URL=$(app_url vendor-management-portal)"
  "NEXT_PUBLIC_PROCUREMENT_APP_URL=$(app_url procurement-dashboard)"
  "NEXT_PUBLIC_INVENTORY_APP_URL=$(app_url inventory-control-center)"
  "NEXT_PUBLIC_RECEIVING_APP_URL=$(app_url warehouse-receiving-app)"
  "NEXT_PUBLIC_WAREHOUSE_APP_URL=$(app_url warehouse-floor-app)"
  "NEXT_PUBLIC_POS_APP_URL=$(app_url pos-terminal-app)"
  "NEXT_PUBLIC_STORE_MANAGER_APP_URL=$(app_url store-manager-dashboard)"
  "NEXT_PUBLIC_FINANCE_APP_URL=$(app_url finance-portal)"
)

write() {
  local app="$1"; shift
  printf '%s\n' "# Generated by deploy/frontend-env.sh — do not edit" "$@" "${APP_URLS[@]}" \
    > "frontends/${app}/.env.production.local"
  echo "wrote frontends/${app}/.env.production.local"
}

# Each module app: its own API, its feature flag, and the directory (D-10).
module() {
  local app="$1" svc="$2" flag="$3"; shift 3
  write "$app" \
    "NEXT_PUBLIC_API_URL=$(api_url "$svc")" \
    "NEXT_PUBLIC_FEATURE_${flag}_ENABLED=true" \
    "NEXT_PUBLIC_DIRECTORY_URL=$(api_url directory)" \
    "$@"
}

module vendor-management-portal vendor-management    VENDOR_MANAGEMENT
module procurement-dashboard    procurement          PROCUREMENT \
  "NEXT_PUBLIC_VENDOR_MANAGEMENT_URL=$(api_url vendor-management)"
module inventory-control-center inventory            INVENTORY
module warehouse-receiving-app  receiving            RECEIVING
module warehouse-floor-app      warehouse-operations WAREHOUSE_OPERATIONS
module pos-terminal-app         retail-sales         RETAIL_SALES
module store-manager-dashboard  sales-audit          SALES_AUDIT \
  "NEXT_PUBLIC_RETAIL_SALES_URL=$(api_url retail-sales)" \
  "NEXT_PUBLIC_INVENTORY_URL=$(api_url inventory)"
module finance-portal           financials           FINANCIALS

write executive-dashboard \
  "NEXT_PUBLIC_VENDOR_MANAGEMENT_URL=$(api_url vendor-management)" \
  "NEXT_PUBLIC_PROCUREMENT_URL=$(api_url procurement)" \
  "NEXT_PUBLIC_INVENTORY_URL=$(api_url inventory)" \
  "NEXT_PUBLIC_RECEIVING_URL=$(api_url receiving)" \
  "NEXT_PUBLIC_WAREHOUSE_OPERATIONS_URL=$(api_url warehouse-operations)" \
  "NEXT_PUBLIC_RETAIL_SALES_URL=$(api_url retail-sales)" \
  "NEXT_PUBLIC_SALES_AUDIT_URL=$(api_url sales-audit)" \
  "NEXT_PUBLIC_FINANCIALS_URL=$(api_url financials)" \
  "NEXT_PUBLIC_DIRECTORY_URL=$(api_url directory)"
